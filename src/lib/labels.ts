export function labelOrUnknown(
  labels: Record<number, string>,
  code: number | null | undefined,
  fallback: string,
) {
  if (code === null || code === undefined) {
    return "未知";
  }
  return labels[code] ?? `${fallback} ${code}`;
}

export function displayMonsterName(monster: {
  monsterId: number;
  name: string;
  nameCht: string | null;
  nameEn: string | null;
}) {
  return monster.name || monster.nameCht || monster.nameEn || `#${monster.monsterId}`;
}
